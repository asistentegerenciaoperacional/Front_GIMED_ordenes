async (page) => {
  page.setDefaultTimeout(10000);
  const checks = [], errors = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
  const origin = new URL(page.url()).origin;
  const sid = n => n.toString(16).padStart(24, '0');
  const state = async () => (await page.request.get(origin + '/api/state')).json();
  const command = async (name, payload) => {
    const response = await page.request.post(origin + '/api/commands', { data: { name, payload } });
    if (!response.ok()) throw new Error(await response.text());
    return (await response.json()).result;
  };
  page.on('pageerror', error => errors.push(error.message));
  const initial = await state(), product = initial.productos[0];
  const noCosts = initial.productos.find(p => !initial.costos_maquila.some(c => c.id_producto === p.id));
  const dialog = () => page.getByRole('dialog').last();
  const field = name => dialog().getByRole('textbox', { name, exact: true });
  const save = () => dialog().getByRole('button', { name: 'Guardar registro', exact: true }).click();
  const panel = () => page.locator('.maquila-costs-panel');
  const history = () => panel().locator('.maquila-cost-history').first();
  const row = amount => history().locator('tbody tr').filter({ hasText: amount }).first();
  const add = name => page.getByRole('button', { name: 'Agregar costo de ' + name, exact: true });
  const open = async name => { const button = page.getByRole('button', { name: 'Mostrar costos de ' + name, exact: true }); if (await button.count()) await button.click(); };
  const cancel = async (discard = true) => {
    await dialog().getByRole('button', { name: 'Cancelar', exact: true }).click();
    const confirmation = page.getByRole('alertdialog');
    if (await confirmation.count()) await confirmation.getByRole('button', { name: discard ? 'Descartar cambios' : 'Cancelar', exact: true }).click();
    if (discard) { await page.getByRole('dialog').waitFor({ state: 'hidden' }); await page.waitForTimeout(150); }
  };
  await page.goto(origin + '/catalogos?tab=costos_maquila');
  await panel().waitFor();
  check(await panel().locator('.relation-group-row').count() === 3, 'Por defecto solo productos con costos');
  check(await panel().locator('.relation-group-row strong').allTextContents().then(names => names.join('|') === [...names].sort((a,b) => a.localeCompare(b, 'es')).join('|')), 'Productos ordenados alfabéticamente');
  const filter = page.getByRole('combobox', { name: 'Filtro personalizado de costos', exact: true });
  await filter.selectOption('todos');
  check(await panel().locator('.relation-group-row').count() === initial.productos.length, 'Filtro muestra todos los productos');
  check(await page.getByRole('button', { name: 'Mostrar costos de ' + noCosts.nombre_producto, exact: true }).isDisabled(), 'Producto vacío conserva despliegue bloqueado');
  check(await add(noCosts.nombre_producto).isEnabled(), 'Producto vacío permite agregar');
  await filter.focus(); await filter.press('Space');
  await page.getByRole('option', { name: 'Con costos', exact: true }).press('Enter');
  check(await panel().locator('.relation-group-row').count() === 3, 'Filtro personalizado funciona con teclado');
  await page.getByRole('button', { name: 'Agregar', exact: true }).click();
  await save();
  check(await field('Costo de maquila').getAttribute('aria-invalid') === 'true', 'Importe obligatorio señalado');
  check(await field('Vigente desde').getAttribute('aria-invalid') === 'true', 'Inicio obligatorio señalado');
  await dialog().getByRole('combobox', { name: 'Producto', exact: true }).selectOption(product.id);
  await field('Vigente desde').fill(''); await field('Vigente desde').pressSequentially('01012024');
  check(await field('Vigente desde').inputValue() === '01/01/2024', 'Escritura continua añade separadores sin reinterpretar segmentos parciales');
  await field('Costo de maquila').fill('2500'); await field('Vigente desde').fill('01/01/202');
  check(await field('Vigente desde').inputValue() === '01/01/202', 'Año parcial se conserva en el borrador');
  await save();
  check(await field('Vigente desde').getAttribute('aria-invalid') === 'true', 'Fecha parcial impide guardar');
  await field('Vigente desde').fill('01/01/2024'); await field('Vigente hasta').fill('31/12/2024');
  for (const amount of ['0', '-1', '1.5']) {
    await field('Costo de maquila').fill(amount); await save();
    check(await field('Costo de maquila').getAttribute('aria-invalid') === 'true', 'Rechazo de costo ' + amount);
  }
  await cancel();
  check((await state()).costos_maquila.length === initial.costos_maquila.length, 'Cancelar no guarda el borrador');
  await add(product.nombre_producto).click();
  check(await dialog().getByRole('combobox', { name: 'Producto', exact: true }).isDisabled(), 'Alta desde + tiene producto bloqueado');
  await field('Costo de maquila').fill('3500'); await field('Vigente desde').fill('01/01/2027'); await save();
  check((await dialog().innerText()).includes('Cierra el costo abierto'), 'Segundo periodo abierto exige cerrar el anterior');
  await field('Vigente desde').fill('01/11/2025'); await field('Vigente hasta').fill('01/11/2026'); await save();
  check((await dialog().innerText()).includes('se solapa'), 'Periodo contenido o cruzado rechazado en el formulario');
  await cancel();
  await filter.selectOption('con_costos');
  await open(product.nombre_producto);
  await history().waitFor(); await page.waitForTimeout(220);
  check((await history().locator('tbody tr td:first-child').allTextContents()).join('|') === '$ 3.200,00|$ 2.900,00', 'Historial descendente y completo');
  await page.mouse.move(0, 0);
  check(await row('3.200').locator('.maquila-cost-actions').evaluate(el => getComputedStyle(el).opacity) === '0', 'Acciones ocultas fuera de hover');
  await row('3.200').hover();
  check(await row('3.200').locator('.maquila-cost-actions').evaluate(el => getComputedStyle(el).opacity) === '1', 'Hover muestra lápiz y papelera');
  const edit = row('3.200').getByRole('button', { name: /^Editar costo/ });
  await edit.focus(); await page.mouse.move(0, 0);
  check(await row('3.200').locator('.maquila-cost-actions').evaluate(el => getComputedStyle(el).opacity) === '1', 'Foco de teclado mantiene acciones visibles');
  await edit.click(); await field('Vigente hasta').fill('31/10/2026'); await save();
  await page.getByRole('dialog').waitFor({ state: 'hidden' }); await page.waitForTimeout(150);
  check(await edit.evaluate(el => el === document.activeElement), 'Guardar edición devuelve foco al lápiz');
  await add(product.nombre_producto).click();
  await field('Costo de maquila').fill('3500'); await field('Vigente desde').fill('01/11/2026');
  await page.route('**/api/commands', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Error temporal de prueba', code: 'SERVER' }) }));
  await save(); await dialog().getByText('Error temporal de prueba', { exact: true }).waitFor();
  check(await field('Costo de maquila').inputValue() === '3500', 'Error de servicio conserva el borrador');
  await page.unroute('**/api/commands');
  let requests = 0;
  await page.route('**/api/commands', async route => { requests++; await new Promise(ok => setTimeout(ok, 350)); await route.continue(); });
  await save(); await page.keyboard.press('Escape');
  await dialog().locator('form').evaluate(form => form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })));
  check(await dialog().isVisible(), 'Guardado bloquea el cierre con Escape');
  check(await dialog().getByRole('button', { name: 'Cancelar', exact: true }).isDisabled(), 'Guardado bloquea Cancelar');
  await page.getByRole('dialog').waitFor({ state: 'hidden' }); await page.unroute('**/api/commands');
  check(requests === 1, 'Guardado envía una sola solicitud');
  let db = await state();
  check(db.costos_maquila.filter(c => c.id_producto === product.id).length === 3, 'Cierre y alta guardan un historial válido');
  check(JSON.stringify(db.orden_producto) === JSON.stringify(initial.orden_producto), 'Las órdenes conservan sus precios históricos');
  await add(product.nombre_producto).click();
  await field('Costo de maquila').fill('3600'); await field('Vigente desde').fill('01/01/2024'); await field('Vigente hasta').fill('31/12/2024');
  await command('saveEntity', { entity: 'costos_maquila', row: { id: sid(850), id_producto: product.id, costo: 2400, fecha_inicio: '2024-01-01T12:00:00Z', fecha_fin: '2024-12-31T12:00:00Z' } });
  await save(); await dialog().getByText('Revisa el periodo del costo de maquila.', { exact: true }).waitFor();
  check(await field('Costo de maquila').inputValue() === '3600' && (await dialog().innerText()).includes('2.400'), 'Conflicto concurrente conserva selección y muestra el costo incompatible');
  await cancel();
  const search = page.getByRole('textbox', { name: 'Buscar costos de maquila', exact: true });
  for (const value of ['2900', '2025-01-01', '01/01/2025', product.nombre_producto]) {
    await search.fill(value); await page.waitForTimeout(120);
    check(await panel().locator('.relation-group-row').count() === 1 && await history().locator('tbody tr').count() === 4, 'Buscar ' + value + ' muestra el historial completo');
  }
  await search.fill('no-hay-coincidencias'); await page.getByText('Sin coincidencias', { exact: true }).waitFor();
  check(await panel().locator('.relation-group-row').count() === 0, 'Búsqueda sin resultados');
  await search.fill('');
  await filter.selectOption('todos');
  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    const filterBounds = await filter.boundingBox(), addBounds = await page.getByRole('button', { name: 'Agregar', exact: true }).boundingBox();
    check(Math.abs(filterBounds.y - addBounds.y) <= 3, 'Filtro y Agregar comparten fila a ' + width + 'px');
    await add(noCosts.nombre_producto).scrollIntoViewIfNeeded();
    const scrollBefore = await page.evaluate(() => window.scrollY);
    await add(noCosts.nombre_producto).click();
    check(await dialog().getByRole('combobox', { name: 'Producto', exact: true }).isDisabled(), 'Producto bloqueado a ' + width + 'px');
    await field('Costo de maquila').fill('2300'); await field('Vigente desde').fill('01/01/2023'); await field('Vigente hasta').fill('31/12/2023');
    check(await dialog().evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Diálogo contenido a ' + width + 'px');
    await page.screenshot({ path: 'tests/evidence/costs/editor-' + width + '.png', fullPage: false });
    if (width === 375) {
      await cancel(false);
      check(await field('Costo de maquila').inputValue() === '2300', 'Cancelar descarte conserva el borrador');
    }
    await cancel();
    check(Math.abs(await page.evaluate(() => window.scrollY) - scrollBefore) <= 2, 'Cerrar conserva scroll a ' + width + 'px');
    check(await add(noCosts.nombre_producto).evaluate(el => el === document.activeElement), 'Cancelar devuelve foco al + a ' + width + 'px');
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Página contenida a ' + width + 'px');
    await page.screenshot({ path: 'tests/evidence/costs/groups-' + width + '.png', fullPage: true });
  }
  await add(noCosts.nombre_producto).click(); await field('Costo de maquila').fill('2300'); await field('Vigente desde').fill('01/01/2023'); await save(); await page.getByRole('dialog').waitFor({ state: 'hidden' });
  check((await state()).costos_maquila.some(c => c.id_producto === noCosts.id), 'Configurar producto antes vacío');
  await filter.selectOption('con_costos');
  await open(noCosts.nombre_producto);
  const newHistory = panel().locator('.maquila-cost-history').filter({ has: page.getByText('$ 2.300,00', { exact: true }) });
  await newHistory.locator('tbody tr').hover();
  await newHistory.getByRole('button', { name: /^Eliminar costo/ }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Eliminar costo', exact: true }).click();
  await page.waitForTimeout(250);
  check(!((await state()).costos_maquila.some(c => c.id_producto === noCosts.id)), 'Eliminar último costo retira el grupo del filtro Con costos');
  check(await page.getByRole('button', { name: 'Agregar', exact: true }).evaluate(el => el === document.activeElement), 'Grupo eliminado devuelve foco a Agregar');
  await command('saveEntity', { entity: 'productos', row: { ...product, id: sid(890) } });
  await page.reload(); await filter.selectOption('todos');
  check(await panel().locator('.relation-group-row strong').filter({ hasText: product.nombre_producto }).count() === 2, 'Productos homónimos se mantienen separados por identificador');
  const touch = await page.context().browser().newContext({ hasTouch: true, viewport: { width: 375, height: 900 } });
  const touchPage = await touch.newPage();
  await touchPage.goto(origin + '/catalogos?tab=costos_maquila');
  await touchPage.getByRole('button', { name: /^Mostrar costos de Crema corporal/ }).first().click();
  check(await touchPage.locator('.maquila-cost-actions').first().evaluate(el => getComputedStyle(el).opacity) === '1', 'Acciones visibles sin hover en dispositivo táctil');
  await touchPage.screenshot({ path: 'tests/evidence/costs/touch-375.png', fullPage: true });
  await touch.close();
  check(errors.length === 0, 'Sin errores de ejecución');
  return { checks, errors };
}
