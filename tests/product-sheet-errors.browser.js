async (page) => {
  page = page.context().pages()[0];
  page.setDefaultTimeout(12000);
  const origin = new URL(page.url()).origin;
  const checks = [], errors = [];
  const check = (value, label) => {
    if (!value) throw new Error(label);
    checks.push(label);
  };
  page.on("pageerror", (error) => errors.push(error.message));
  const state = async () => (await page.request.get(origin + "/api/state")).json();
  const command = async (name, payload) => {
    const response = await page.request.post(origin + "/api/commands", { data: { name, payload } });
    if (!response.ok()) throw new Error(await response.text());
    return (await response.json()).result;
  };
  const initial = await state();
  const product = initial.productos.find((p) => p.activo && initial.codigos_barras.some((code) => code.id_producto === p.id && code.estado === "asignado"));
  const created = await command("createOrder", { tipo_orden: "producto", id_proveedor: product.id_maquilador, fecha_solicitada_entrega: "2099-02-15T12:00:00.000Z", lines: [{ id_producto: product.id, cantidad_solicitada: 1000, precio_unitario: "2.50" }] });
  await command("authorizeOrder", { id: created.orderId, confirm: true });
  const db = await state(), order = db.orden_compra.find((row) => row.id === created.orderId);
  await page.evaluate(() => localStorage.setItem("gimed:ui:product-order-sheet", "true"));
  await page.goto(origin + "/ordenes/productos?q=" + order.no_orden);
  await page.setViewportSize({ width: 1440, height: 900 });
  const { sheetCell } = await import((await import("node:url")).pathToFileURL((await import("node:path")).resolve("tests/sheet-locator.mjs")).href);
  const cell = (key) => sheetCell(page, 0, key);
  const grid = page.locator(".product-sheet-viewport");
  const banner = page.locator(".product-sheet-error-notice");
  await cell("precio_unitario").click();
  await page.keyboard.press("Delete");
  const priceInput = page.getByRole("textbox", { name: "Precio unitario" });
  check((await priceInput.inputValue()) === "" && !(await banner.count()), "Supr deja la celda numérica vacía sin mostrar un error");
  await page.keyboard.press("ArrowUp");
  check((await priceInput.inputValue()) === "" && !(await banner.count()), "Permanecer en la misma celda no activa la validación");
  await priceInput.fill("4");
  await page.keyboard.press("ArrowRight");
  check((await cell("precio_unitario").innerText()).includes("4,00"), "El precio válido queda en el borrador");
  await cell("precio_unitario").click();
  await page.keyboard.press("Delete");
  check((await priceInput.inputValue()) === "" && !(await banner.count()), "Supr permite dejar temporalmente vacío el precio obligatorio");
  await page.keyboard.press("ArrowRight");
  await banner.waitFor();
  check((await cell("precio_unitario").innerText()).includes("4,00"), "Al salir de un precio vacío se rechaza y se conserva el borrador");
  await page.getByRole("button", { name: "Cerrar aviso de error" }).click();
  await cell("precio_unitario").dblclick();
  await page.getByRole("textbox", { name: "Precio unitario" }).fill("-3");
  await page.keyboard.press("Enter");
  await banner.waitFor();
  check((await cell("precio_unitario").innerText()).includes("4,00"), "Precio inválido se revierte al valor del borrador");
  check((await cell("precio_unitario").getAttribute("data-rejected")) !== null, "Precio rechazado conserva marca");
  check((await page.locator('[aria-label="Celdas rechazadas"]').count()) === 0, "Sin lista de celdas rechazadas");
  await page.getByRole("button", { name: "Cerrar aviso de error" }).click();
  check(!(await banner.count()) && (await cell("precio_unitario").getAttribute("data-rejected")) === null, "Cerrar aviso elimina las marcas de error");
  await cell("numero_lote").click();
  check((await cell("numero_lote").getAttribute("data-active")) !== null, "Selección inmediata tras error");
  await cell("codigo").click();
  await page.keyboard.press("F2");
  await banner.waitFor();
  check((await cell("codigo").getAttribute("data-rejected")) !== null, "Nuevo error protegido muestra aviso");
  const oldDate = await cell("fecha_solicitada_entrega").innerText();
  await cell("fecha_solicitada_entrega").dblclick();
  await page.getByRole("textbox", { name: "Fecha solicitada de entrega" }).fill("31022027");
  await page.keyboard.press("Enter");
  check((await cell("fecha_solicitada_entrega").innerText()) === oldDate, "Fecha inválida se revierte");
  check((await cell("fecha_solicitada_entrega").getAttribute("data-rejected")) !== null, "Fecha inválida conserva marca");
  await cell("id_factura").dblclick();
  check((await page.locator(".sheet-reference-editor").boundingBox()).width >= 350, "El selector de factura conserva su ancho amplio");
  check(await page.getByRole("button", { name: "Agregar factura" }).isVisible(), "El botón de agregar factura conserva su texto");
  await page.getByRole("combobox", { name: "Buscar número de factura" }).fill("FACTURA-INEXISTENTE-987654");
  await cell("no_orden").click();
  await banner.waitFor();
  check((await cell("id_factura").getAttribute("data-rejected")) !== null, "Factura inexistente se rechaza");
  check((await cell("no_orden").getAttribute("data-active")) !== null, "Se puede salir inmediatamente del autocompletado");
  await cell("ref_corrugado").dblclick();
  check((await page.locator(".sheet-reference-editor").boundingBox()).width >= 350, "El selector de corrugado tiene espacio para sus opciones");
  await page.keyboard.press("Escape");
  await cell("numero_lote").dblclick();
  await page.getByRole("textbox", { name: "Lote" }).fill("PRUEBA-UBICACION");
  await page.keyboard.press("Enter");
  await cell("ubicacion").dblclick();
  const locationInput = page.getByRole("combobox", { name: "Buscar ubicación" });
  check(await locationInput.isVisible(), "Ubicación ofrece búsqueda de referencias");
  const locationEditor = await page.locator(".sheet-reference-editor").boundingBox();
  const locationCell = await cell("ubicacion").boundingBox();
  check(Math.abs(locationEditor.x + locationEditor.width - locationCell.x - locationCell.width) < 3, "El editor de ubicación se despliega hacia la izquierda");
  await page.getByRole("button", { name: "Agregar dirección" }).click();
  check(await page.getByRole("dialog", { name: /Agregar.*Direcciones/ }).isVisible(), "Agregar abre el formulario de dirección");
  const addressDialog = page.getByRole("dialog", { name: /Agregar.*Direcciones/ });
  await addressDialog.getByRole("button", { name: "Tipo de ubicación" }).click();
  await page.getByRole("option", { name: "Propia", exact: true }).click();
  await addressDialog.getByRole("textbox", { name: "Nombre de la bodega" }).fill("Bodega prueba hoja");
  await addressDialog.getByRole("textbox", { name: "Ciudad" }).fill("Bogotá");
  await addressDialog.getByRole("button", { name: "Guardar registro" }).click();
  await addressDialog.waitFor({ state: "hidden" });
  await page.waitForFunction(() => [...document.querySelectorAll('[data-column-key="ubicacion"]')].some((cell) => cell.textContent.includes("Bodega prueba hoja")));
  check((await cell("ubicacion").innerText()).includes("Bodega prueba hoja"), "La nueva dirección queda seleccionada en el borrador");
  await cell("precio_unitario").click();
  await grid.evaluate((element) => {
    const data = new DataTransfer();
    data.setData("text/plain", "-2\t-5");
    element.dispatchEvent(new ClipboardEvent("paste", { bubbles: true, clipboardData: data }));
  });
  await banner.waitFor();
  check((await banner.innerText()).includes("2 celdas"), "Pegado inválido se resume en el banner");
  check((await page.locator(".product-sheet-errors").count()) === 0, "No aparece lista para pegados");
  await page.getByRole("button", { name: /Guardar 3 cambios/ }).click();
  const saved = await state();
  check(saved.orden_producto.find((line) => line.id_orden_compra === order.id).precio_unitario === "4.00", "Guardar conserva el borrador válido y excluye valores rechazados");
  const createdAddress = saved.direccion.find((address) => address.nombre_dir === "Bodega prueba hoja");
  check(saved.lote_producto.some((lot) => lot.numero_lote === "PRUEBA-UBICACION" && lot.id_direccion === createdAddress.id), "Guardar persiste la dirección seleccionada en el lote");
  await cell("ubicacion").dblclick();
  await page.getByRole("combobox", { name: "Buscar ubicación" }).fill("Bodega principal");
  await page.getByRole("option", { name: /Bodega principal/ }).first().click();
  check((await cell("ubicacion").innerText()).includes("Bodega principal"), "La búsqueda permite seleccionar una ubicación existente");
  await cell("precio_unitario").dblclick();
  await page.getByRole("textbox", { name: "Precio unitario" }).fill("-6");
  await page.getByRole("button", { name: "Anuladas", exact: true }).click();
  check(new URL(page.url()).searchParams.get("vista") === "anuladas", "Cambiar de hoja no queda bloqueado por el valor inválido");
  return { checks, errors };
}
