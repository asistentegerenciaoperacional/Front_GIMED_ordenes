async (page) => {
  page = page.context().pages()[0];
  page.setDefaultTimeout(12000);
  const origin = new URL(page.url()).origin, checks = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
  const state = async () => (await page.request.get(origin + "/api/state")).json();
  const command = async (name, payload) => {
    const response = await page.request.post(origin + "/api/commands", { data: { name, payload } });
    if (!response.ok()) throw new Error(await response.text());
    return (await response.json()).result;
  };
  let db = await state();
  const product = db.productos.find((p) => p.activo && db.codigos_barras.some((b) => b.id_producto === p.id && b.estado === "asignado"));
  const created = await command("createOrder", { tipo_orden: "producto", id_proveedor: product.id_maquilador, fecha_solicitada_entrega: "2099-03-15T12:00:00.000Z", lines: [{ id_producto: product.id, cantidad_solicitada: 100, precio_unitario: "2.50" }] });
  db = await state();
  const order = db.orden_compra.find((o) => o.id === created.orderId);
  const line = db.orden_producto.find((l) => l.id_orden_compra === order.id);
  await page.evaluate(() => localStorage.setItem("gimed:ui:product-order-sheet", "true"));
  await page.goto(origin + "/ordenes/productos?vista=no_autorizadas&q=" + order.no_orden);
  await page.locator(".product-order-sheet").waitFor();
  const waitReady = async () => { await page.locator('.product-order-sheet[aria-busy="false"]').waitFor(); await page.waitForTimeout(300); };
  const firstCell = () => page.locator('.product-sheet-grid tbody [data-sheet-row="0"]').first();
  await firstCell().click();
  await page.keyboard.press("Alt+a");
  const auth = page.getByRole("dialog").last();
  await auth.waitFor();
  check((await auth.innerText()).includes("Autorizar"), "Alt+A abre autorización de la selección");
  await auth.getByRole("button", { name: /Cancelar|Cerrar/ }).first().click();
  await command("authorizeOrder", { id: order.id, confirm: true });
  db = await state();
  const initial = db.lote_producto.find((lot) => lot.id_orden_producto === line.id);
  const lotCell = () => page.locator(`[data-sheet-key="lot:${initial.id}"]`).first();
  await command("saveLot", { row: { ...initial, numero_lote: "ATAJO-1" } });
  await command("saveLot", { row: { id_orden_producto: line.id, numero_lote: "ATAJO-2", estado: "en_seguimiento" } });
  await page.goto(origin + "/ordenes/productos?vista=seguimiento&q=" + order.no_orden);
  await page.locator(".product-order-sheet").waitFor();
  await firstCell().click();
  await page.keyboard.press("Alt+o");
  const create = page.getByRole("dialog", { name: "Nueva orden de compra" });
  await create.waitFor();
  await create.getByRole("button", { name: "Cancelar", exact: true }).click();
  check(true, "Alt+O abre nueva orden");
  await firstCell().click();
  const colsBefore = Number(await page.locator(".product-sheet-grid").getAttribute("aria-colcount"));
  await page.keyboard.press("Alt+Shift+h");
  check(Number(await page.locator(".product-sheet-grid").getAttribute("aria-colcount")) === colsBefore, "Alt+Mayús+H ya no oculta columnas");
  await page.keyboard.press("Alt+h");
  await page.waitForFunction((n) => Number(document.querySelector(".product-sheet-grid").getAttribute("aria-colcount")) < n, colsBefore);
  await page.keyboard.press("Alt+s");
  await page.waitForFunction((n) => Number(document.querySelector(".product-sheet-grid").getAttribute("aria-colcount")) === n, colsBefore);
  check(true, "Alt+H oculta y Alt+S muestra columnas");
  await firstCell().click();
  await page.keyboard.press("Alt+d");
  await page.waitForFunction(async (id) => (await (await fetch('/api/state')).json()).lote_producto.filter((l) => l.id_orden_producto === id).length === 3, line.id);
  await waitReady();
  check(true, "Alt+D crea un lote");
  await lotCell().click();
  await page.keyboard.press("Alt+c");
  await page.waitForFunction(async (id) => (await (await fetch('/api/state')).json()).lote_producto.find((l) => l.id === id)?.estado === 'cerrado', initial.id);
  await page.locator(`tr[data-lot-state="cerrado"] [data-sheet-key="lot:${initial.id}"]`).first().waitFor();
  await waitReady();
  check(true, "Alt+C cierra el lote seleccionado");
  await lotCell().click();
  await page.locator("[data-active]").waitFor();
  await page.keyboard.press("Alt+n");
  let confirmation = page.getByRole("alertdialog");
  await confirmation.waitFor();
  await confirmation.getByRole("button", { name: "Anular lote", exact: true }).click();
  await page.waitForFunction(async (id) => (await (await fetch('/api/state')).json()).lote_producto.find((l) => l.id === id)?.estado === 'anulado', initial.id);
  await waitReady();
  check(true, "Alt+N confirma la anulación del lote");
  await page.getByRole("button", { name: "Anuladas", exact: true }).click();
  await lotCell().click();
  await page.keyboard.press("Alt+r");
  await page.waitForFunction(async (id) => (await (await fetch('/api/state')).json()).lote_producto.find((l) => l.id === id)?.estado === 'en_seguimiento', initial.id);
  await waitReady();
  check(true, "Alt+R reabre el lote");
  await page.getByRole("button", { name: "En seguimiento", exact: true }).click();
  await firstCell().click();
  await page.locator('.product-sheet-grid tbody [data-sheet-row="1"]').first().click({ modifiers: ["Shift"] });
  const before = await state();
  await page.keyboard.press("Alt+Delete");
  const dialog = page.getByRole("dialog", { name: "Eliminar lote", exact: true });
  await dialog.waitFor();
  const matchingTextStyle = await dialog.evaluate((node) => {
    const paragraph = getComputedStyle(node.querySelector(".dialog-body > p"));
    const item = getComputedStyle(node.querySelector(".delete-lot-list li"));
    return ["fontFamily", "fontSize", "fontWeight", "lineHeight", "color"].every((key) => paragraph[key] === item[key]);
  });
  check(matchingTextStyle, "La lista de lotes comparte tipografía y color con el mensaje");
  check(await dialog.locator("li").count() === 2 && (await dialog.innerText()).includes(order.no_orden) && (await dialog.innerText()).includes(product.nombre_producto), "Alt+Supr muestra lista de lotes, producto y OC");
  await dialog.getByRole("button", { name: "Cancelar", exact: true }).click();
  check(JSON.stringify(await state()) === JSON.stringify(before), "Cancelar eliminación conserva todos los datos");
  await page.getByRole("button", { name: "Eliminar lotes seleccionados" }).click();
  await dialog.getByRole("button", { name: "Eliminar lote", exact: true }).click();
  await page.waitForFunction(async (id) => (await (await fetch('/api/state')).json()).lote_producto.filter((l) => l.id_orden_producto === id).length === 1, line.id);
  check(true, "Papelera elimina los lotes seleccionados conjuntamente");
  return { checks };
};
